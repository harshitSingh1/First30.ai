import { useState } from 'react';
import { Copy, Check, FileText, Clock, CheckCircle2, AlertCircle, Download, Printer, ShieldCheck } from 'lucide-react';
import { Button } from '@/components/ui/button';
import { useLanguage } from '@/contexts/LanguageContext';
import { CollectedInput } from '@/types/emergency';
import { toast } from '@/hooks/use-toast';
import { cn } from '@/lib/utils';
import { downloadEmergencyCardPdf } from '@/utils/pdfGenerator';

interface EmergencySummaryCardProps {
  category: string;
  collectedInputs: CollectedInput[];
  stepsCompleted: string[];
  totalSteps: number;
  duration: number;
  recommendations?: string[];
  className?: string;
}

const EmergencySummaryCard = ({
  category,
  collectedInputs,
  stepsCompleted,
  totalSteps,
  duration,
  recommendations,
  className,
}: EmergencySummaryCardProps) => {
  const [copied, setCopied] = useState(false);
  const { t } = useLanguage();

  const formatDuration = (seconds: number): string => {
    const mins = Math.floor(seconds / 60);
    const secs = seconds % 60;
    return `${mins}m ${secs}s`;
  };

  const generateSummaryText = (): string => {
    const uniqueSteps = Array.from(new Set(stepsCompleted));
    const safeTotal = Math.max(totalSteps, uniqueSteps.length, 1);
    const completedCount = Math.min(uniqueSteps.length, safeTotal);
    const pct = Math.min(100, Math.max(0, Math.round((completedCount / safeTotal) * 100)));

    let summary = `====================================================\n`;
    summary += `         FIRST30.AI — EMERGENCY SUMMARY            \n`;
    summary += `====================================================\n\n`;
    summary += `Emergency Category : ${category}\n`;
    summary += `Date & Time        : ${new Date().toLocaleString()}\n`;
    summary += `Total Duration     : ${formatDuration(duration)}\n`;
    summary += `Steps Completed    : ${completedCount} of ${safeTotal} (${pct}%)\n\n`;

    if (collectedInputs.length > 0) {
      summary += `----------------------------------------------------\n`;
      summary += `ASSESSMENT & OBSERVATIONS\n`;
      summary += `----------------------------------------------------\n`;
      collectedInputs.forEach((input, index) => {
        summary += `${index + 1}. ${input.question}\n   Response: ${input.answer}\n`;
      });
      summary += `\n`;
    }

    if (uniqueSteps.length > 0) {
      summary += `----------------------------------------------------\n`;
      summary += `COMPLETED PROTOCOL STEPS\n`;
      summary += `----------------------------------------------------\n`;
      uniqueSteps.forEach((step, index) => {
        summary += `[✓] Step ${index + 1}: ${step}\n`;
      });
      summary += `\n`;
    }

    if (recommendations && recommendations.length > 0) {
      summary += `----------------------------------------------------\n`;
      summary += `CLINICAL RECOMMENDATIONS FOR ARRIVING PARAMEDICS\n`;
      summary += `----------------------------------------------------\n`;
      recommendations.forEach((rec) => {
        summary += `• ${rec}\n`;
      });
      summary += `\n`;
    }

    summary += `====================================================\n`;
    summary += `Generated by First30.ai Emergency Response System\n`;
    summary += `Verified bystander on-scene record.\n`;
    summary += `====================================================\n`;

    return summary;
  };

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(generateSummaryText());
      setCopied(true);
      toast({
        title: 'Copied to clipboard!',
        description: 'Emergency summary copied to clipboard',
      });
      setTimeout(() => setCopied(false), 2000);
    } catch {
      toast({
        title: 'Copy failed',
        description: 'Please try again',
        variant: 'destructive',
      });
    }
  };

  const handleDownload = () => {
    try {
      const summaryText = generateSummaryText();
      const safeCategory = category.toLowerCase().replace(/[^a-z0-9]/g, '-');
      const filename = `First30-Emergency-Summary-${safeCategory}-${new Date().toISOString().slice(0, 10)}.txt`;

      const blob = new Blob([summaryText], { type: 'text/plain;charset=utf-8' });
      const url = URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url;
      link.download = filename;
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      URL.revokeObjectURL(url);

      toast({
        title: 'Summary Downloaded!',
        description: `Saved as ${filename}`,
      });
    } catch {
      toast({
        title: 'Download failed',
        description: 'Unable to download file on this device',
        variant: 'destructive',
      });
    }
  };

  const handlePrint = () => {
    try {
      const uniqueSteps = Array.from(new Set(stepsCompleted));
      const safeTotal = Math.max(totalSteps, uniqueSteps.length, 1);
      const completedCount = Math.min(uniqueSteps.length, safeTotal);

      const generated = downloadEmergencyCardPdf({
        category,
        duration: formatDuration(duration),
        completedStepsCount: completedCount,
        totalStepsCount: safeTotal,
        stepsCompleted: uniqueSteps,
        collectedInputs,
        recommendations,
      });

      if (generated) {
        toast({
          title: 'PDF Saved Successfully!',
          description: 'Emergency Protocol Summary PDF downloaded to your device',
        });
      } else {
        handleDownload();
      }

      // Also invoke native print dialog if supported by the browser context
      if (typeof window !== 'undefined' && window.print) {
        try {
          window.print();
        } catch {
          // Handled silently if in sandboxed iframe since PDF is already downloaded
        }
      }
    } catch {
      handleDownload();
    }
  };

  const uniqueSteps = Array.from(new Set(stepsCompleted));
  const safeTotal = Math.max(totalSteps, uniqueSteps.length, 1);
  const completedCount = Math.min(uniqueSteps.length, safeTotal);
  const completionPct = Math.min(100, Math.max(0, Math.round((completedCount / safeTotal) * 100)));

  return (
    <div className={cn('premium-card p-6 md:p-8 space-y-5', className)}>
      {/* Header */}
      <div className="flex items-center justify-between pb-4 border-b border-border/50">
        <div className="flex items-center gap-2.5">
          <FileText className="w-6 h-6 text-primary shrink-0" />
          <div>
            <h3 className="font-bold text-lg text-foreground">{t('emergencySummary') || 'Emergency Protocol Summary'}</h3>
            <p className="text-xs text-muted-foreground">Recorded by bystander on scene</p>
          </div>
        </div>
        <span className="inline-flex items-center gap-1 px-2.5 py-1 rounded-full text-xs font-semibold bg-emerald-500/15 text-emerald-400 border border-emerald-500/30">
          <ShieldCheck className="w-3.5 h-3.5" />
          Completed
        </span>
      </div>

      {/* Primary Metrics Grid */}
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
        {/* Emergency Type */}
        <div className="p-3.5 rounded-xl bg-secondary/40 border border-border/40">
          <div className="flex items-center gap-1.5 text-xs text-muted-foreground mb-1">
            <AlertCircle className="w-3.5 h-3.5 text-primary" />
            <span>Category</span>
          </div>
          <p className="font-semibold text-sm text-foreground truncate">{category}</p>
        </div>

        {/* Frozen Completed Duration */}
        <div className="p-3.5 rounded-xl bg-secondary/40 border border-border/40">
          <div className="flex items-center gap-1.5 text-xs text-muted-foreground mb-1">
            <Clock className="w-3.5 h-3.5 text-amber-400" />
            <span>Total Duration</span>
          </div>
          <p className="font-semibold text-sm font-mono text-foreground">{formatDuration(duration)}</p>
        </div>

        {/* Steps Progress */}
        <div className="p-3.5 rounded-xl bg-secondary/40 border border-border/40">
          <div className="flex items-center gap-1.5 text-xs text-muted-foreground mb-1">
            <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400" />
            <span>Protocol Progress</span>
          </div>
          <p className="font-semibold text-sm text-foreground">
            {completedCount}/{safeTotal} ({completionPct}%)
          </p>
          <div className="w-full h-1.5 bg-background rounded-full overflow-hidden mt-1.5">
            <div
              className="h-full bg-emerald-500 rounded-full transition-all duration-500"
              style={{ width: `${completionPct}%` }}
            />
          </div>
        </div>
      </div>

      {/* Complete Assessment Answers */}
      {collectedInputs.length > 0 && (
        <div className="pt-2">
          <h4 className="text-sm font-semibold text-foreground mb-2.5 flex items-center gap-2">
            <span>Assessment &amp; Bystander Responses</span>
            <span className="text-xs text-muted-foreground font-normal">({collectedInputs.length} recorded)</span>
          </h4>
          <div className="space-y-2">
            {collectedInputs.map((input, index) => (
              <div key={index} className="p-3 rounded-xl bg-secondary/30 border border-border/30 text-xs">
                <p className="text-muted-foreground font-medium mb-1">{input.question}</p>
                <p className="font-semibold text-foreground text-sm flex items-center gap-1.5">
                  <span className="w-2 h-2 rounded-full bg-primary shrink-0" />
                  {input.answer}
                </p>
              </div>
            ))}
          </div>
        </div>
      )}

      {/* Complete Steps Completed List */}
      {uniqueSteps.length > 0 && (
        <div className="pt-2">
          <h4 className="text-sm font-semibold text-foreground mb-2.5 flex items-center gap-2">
            <CheckCircle2 className="w-4 h-4 text-emerald-400 shrink-0" />
            <span>Steps Completed by Bystander</span>
            <span className="text-xs text-muted-foreground font-normal">({completedCount} steps)</span>
          </h4>
          <div className="space-y-1.5 max-h-56 overflow-y-auto pr-1">
            {uniqueSteps.map((step, index) => (
              <div key={index} className="flex items-center gap-2.5 text-xs bg-secondary/30 border border-border/30 px-3 py-2.5 rounded-xl">
                <span className="w-5 h-5 rounded-full bg-emerald-500/20 text-emerald-400 font-bold flex items-center justify-center shrink-0 text-xs">
                  ✓
                </span>
                <span className="font-medium text-foreground">{step}</span>
              </div>
            ))}
          </div>
        </div>
      )}

      {/* Clinical Recommendations */}
      {recommendations && recommendations.length > 0 && (
        <div className="pt-2">
          <h4 className="text-sm font-semibold text-foreground mb-2 flex items-center gap-2">
            <span>Paramedic Handoff Notes</span>
          </h4>
          <ul className="space-y-1.5">
            {recommendations.map((rec, index) => (
              <li key={index} className="text-xs text-muted-foreground flex items-start gap-2 bg-secondary/20 p-2.5 rounded-xl border border-border/20">
                <span className="w-1.5 h-1.5 rounded-full bg-amber-400 mt-1.5 shrink-0" />
                <span className="text-foreground/90 font-medium">{rec}</span>
              </li>
            ))}
          </ul>
        </div>
      )}

      {/* Proper Download, Copy, and Print Action Bar */}
      <div className="pt-4 border-t border-border/50">
        <p className="text-xs text-muted-foreground mb-3 text-center sm:text-left">
          Export or share this incident record for paramedic and hospital triage:
        </p>
        <div className="grid grid-cols-1 sm:grid-cols-3 gap-2.5">
          <Button
            type="button"
            onClick={handleDownload}
            className="w-full h-11 rounded-xl bg-primary hover:bg-primary/90 text-primary-foreground font-bold text-xs gap-2 shadow-sm"
          >
            <Download className="w-4 h-4" />
            <span>Download (.txt)</span>
          </Button>

          <Button
            type="button"
            variant="outline"
            onClick={handleCopy}
            className="w-full h-11 rounded-xl text-xs font-semibold gap-2 border-border hover:bg-muted"
          >
            {copied ? (
              <>
                <Check className="w-4 h-4 text-emerald-500" />
                <span>Copied!</span>
              </>
            ) : (
              <>
                <Copy className="w-4 h-4" />
                <span>{t('copySummary') || 'Copy Summary'}</span>
              </>
            )}
          </Button>

          <Button
            type="button"
            variant="outline"
            onClick={handlePrint}
            className="w-full h-11 rounded-xl text-xs font-semibold gap-2 border-border hover:bg-muted"
            title="Save as PDF or Print"
          >
            <Printer className="w-4 h-4 text-primary" />
            <span>Save PDF / Print</span>
          </Button>
        </div>
      </div>
    </div>
  );
};

export default EmergencySummaryCard;
